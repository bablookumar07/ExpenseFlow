
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

import {
  filterTransactionsByDateRange,
  getExportRangeLabel,
} from "./exportUtils";

const formatAmount = (amount, currency) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency,
    maximumFractionDigits: 2,
  }).format(amount);

export const exportTransactionsToPDF = ({
  transactions,
  options,
  currency,
  convertAmount,
  userName,
}) => {
  const filtered = filterTransactionsByDateRange(
    transactions,
    options
  );

  if (!filtered.length) {
    throw new Error(
      "No transactions found for the selected date range."
    );
  }

  const income = filtered
    .filter((item) => item.type === "income")
    .reduce(
      (total, item) =>
        total + convertAmount(Number(item.amount) || 0),
      0
    );

  const expenses = filtered
    .filter((item) => item.type === "expense")
    .reduce(
      (total, item) =>
        total + convertAmount(Number(item.amount) || 0),
      0
    );

  const balance = income - expenses;

  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Header
  doc.setFillColor(91, 63, 190);
  doc.rect(0, 0, pageWidth, 42, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(23);
  doc.text("ExpenseFlow", 14, 17);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Personal Financial Report", 14, 25);

  doc.setFontSize(9);
  doc.text(
    `Generated: ${new Date().toLocaleDateString("en-IN")}`,
    pageWidth - 14,
    17,
    { align: "right" }
  );

  // Account details
  doc.setTextColor(35, 35, 45);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text("Account Holder", 14, 53);

  doc.setFont("helvetica", "normal");
  doc.text(userName || "ExpenseFlow User", 14, 60);

  doc.setFont("helvetica", "bold");
  doc.text("Report Period", pageWidth / 2, 53);

  doc.setFont("helvetica", "normal");
  doc.text(getExportRangeLabel(options), pageWidth / 2, 60);

  // Summary cards
  const margin = 14;
  const gap = 7;
  const cardY = 70;
  const cardWidth = (pageWidth - margin * 2 - gap * 2) / 3;

  const cards = [
    {
      title: "TOTAL INCOME",
      value: formatAmount(income, currency),
      color: [16, 145, 95],
    },
    {
      title: "TOTAL EXPENSES",
      value: formatAmount(expenses, currency),
      color: [220, 65, 75],
    },
    {
      title: "NET BALANCE",
      value: formatAmount(balance, currency),
      color: [91, 63, 190],
    },
  ];

  cards.forEach((card, index) => {
    const x = margin + index * (cardWidth + gap);

    doc.setFillColor(246, 247, 251);
    doc.roundedRect(x, cardY, cardWidth, 25, 2, 2, "F");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(105, 105, 120);
    doc.text(card.title, x + 5, cardY + 8);

    doc.setFontSize(12);
    doc.setTextColor(...card.color);
    doc.text(card.value, x + 5, cardY + 18);
  });

  // Transaction table
  const rows = [...filtered]
    .sort(
      (a, b) =>
        new Date(b.date).getTime() -
        new Date(a.date).getTime()
    )
    .map((item) => [
      item.title || "Untitled",
      formatAmount(
        convertAmount(Number(item.amount) || 0),
        currency
      ),
      item.type === "income" ? "Income" : "Expense",
      item.category || "Other",
      item.date
        ? new Date(item.date).toLocaleDateString("en-IN")
        : "",
    ]);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(35, 35, 45);
  doc.text("Transaction Details", 14, 108);

  autoTable(doc, {
    startY: 113,
    head: [
      ["Title", "Amount", "Type", "Category", "Date"],
    ],
    body: rows,
    theme: "grid",
    margin: {
      left: 14,
      right: 14,
      bottom: 18,
    },
    styles: {
      font: "helvetica",
      fontSize: 8,
      cellPadding: 3,
      textColor: [55, 55, 65],
      lineColor: [225, 225, 235],
      lineWidth: 0.15,
      overflow: "linebreak",
    },
    headStyles: {
      fillColor: [91, 63, 190],
      textColor: [255, 255, 255],
      fontStyle: "bold",
    },
    alternateRowStyles: {
      fillColor: [247, 247, 251],
    },
    columnStyles: {
      0: { cellWidth: 65 },
      1: { halign: "right", cellWidth: 35 },
      2: { cellWidth: 30 },
      3: { cellWidth: 55 },
      4: { cellWidth: 35 },
    },
    didDrawPage: () => {
      const pageNumber = doc.internal.getCurrentPageInfo().pageNumber;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(120, 120, 130);

      doc.text(
        "Generated by ExpenseFlow",
        14,
        pageHeight - 8
      );

      doc.text(
        `Page ${pageNumber}`,
        pageWidth - 14,
        pageHeight - 8,
        { align: "right" }
      );
    },
  });

  const dateStamp = new Date().toISOString().slice(0, 10);

  doc.save(`ExpenseFlow_Report_${dateStamp}.pdf`);

  return filtered.length;
};
